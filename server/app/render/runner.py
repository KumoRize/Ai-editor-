"""Rendering (component E): run FFmpeg, report progress, and verify the output.

`render()` never reports success on its own. Success means `verify_output()`
confirmed the file exists, is non-empty, has H.264 video + AAC audio at the
expected size and duration, and decodes from start to end without errors.
"""
from __future__ import annotations

import logging
import os
from pathlib import Path
from typing import Callable

from ..analysis.media import get_video_metadata
from ..config import get_settings
from ..engine.compiler import RenderSpec
from ..errors import EditorError, render_failed
from ..proc import run, run_streaming

log = logging.getLogger(__name__)


def _run_ffmpeg(args: list[str], duration: float, on_frac: Callable[[float], None] | None) -> None:
    s = get_settings()

    def on_line(line: str) -> None:
        if on_frac and line.startswith("out_time_us=") and duration > 0:
            try:
                us = int(line.split("=", 1)[1])
            except ValueError:
                return
            on_frac(max(0.0, min(1.0, us / 1e6 / duration)))

    rc, err_tail = run_streaming(args, timeout=s.render_timeout_s, on_line=on_line)
    if rc != 0:
        Path(args[-1]).unlink(missing_ok=True)
        log.error("ffmpeg failed rc=%s: %s", rc, err_tail)
        raise render_failed(detail=err_tail[-2000:])


def render(spec: RenderSpec, on_progress: Callable[[float], None] | None = None,
           parallel: int | None = None) -> dict:
    """Render all pieces (reusing cached ones, several at a time), then join them. Returns cache stats."""
    import threading
    from concurrent.futures import ThreadPoolExecutor

    out_path = spec.out_path
    out_path.unlink(missing_ok=True)
    # 90% of the bar for pieces (weighted by length), 10% for the final pass.
    total = sum(sg.duration for sg in spec.segments) or 1.0
    lock = threading.Lock()
    done: dict[str, float] = {}
    reused = 0
    last = [0.0]

    def report() -> None:
        if on_progress:
            with lock:
                frac = min(0.9, 0.9 * sum(done.values()) / total)
                if frac > last[0]:
                    last[0] = frac
                    on_progress(frac)

    todo = []
    seen: set[str] = set()
    for sg in spec.segments:
        if sg.out_path.is_file() and sg.out_path.stat().st_size > 0:
            reused += 1
            os.utime(sg.out_path)  # keep cache entries that are still in use
            done[sg.key] = sg.duration
        elif sg.key not in seen:
            seen.add(sg.key)
            todo.append(sg)
    report()

    def work(sg) -> None:
        def on_frac(f: float, sg=sg) -> None:
            done[sg.key] = f * sg.duration
            report()
        _run_ffmpeg(sg.args, sg.duration, on_frac)
        Path(sg.args[-1]).replace(sg.out_path)
        done[sg.key] = sg.duration
        report()

    workers = max(1, parallel or get_settings().render_parallel)
    if workers == 1 or len(todo) <= 1:
        for sg in todo:
            work(sg)
    else:
        with ThreadPoolExecutor(max_workers=workers) as pool:
            futures = [pool.submit(work, sg) for sg in todo]
            errors = [f.exception() for f in futures]
            first = next((e for e in errors if e is not None), None)
            if first is not None:
                raise first

    # Paths are generated by us (hex names in our data dir); quote defensively anyway.
    lines = []
    for sg in spec.segments:
        p = str(sg.out_path.resolve())
        if "'" in p or "\n" in p:
            raise render_failed(detail=f"unsafe segment path {p!r}")
        lines.append(f"file '{p}'")
    spec.concat_list.write_text("\n".join(lines) + "\n")
    try:
        _run_ffmpeg(spec.concat_args, spec.duration,
                    lambda f: on_progress(0.9 + 0.099 * f) if on_progress else None)
    finally:
        spec.concat_list.unlink(missing_ok=True)
    Path(spec.concat_args[-1]).replace(out_path)
    if on_progress:
        on_progress(1.0)
    return {"segments": len(spec.segments), "segments_reused": reused}


def verify_output(path: Path, *, width: int, height: int, duration: float, fps: int,
                  full_decode: bool = True) -> dict:
    """Independent check of the rendered file. Raises EditorError if anything is off."""
    s = get_settings()
    if not path.exists() or path.stat().st_size < 1024:
        raise EditorError("OUTPUT_MISSING", "Rendering produced no output file.", retryable=True)
    try:
        meta = get_video_metadata(path)
    except EditorError as e:
        raise EditorError("OUTPUT_INVALID", "Rendering produced an invalid file.", retryable=True) from e
    problems = []
    if meta.get("vcodec") != "h264":
        problems.append(f"video codec {meta.get('vcodec')} (expected h264)")
    if not meta.get("has_audio") or meta.get("acodec") != "aac":
        problems.append(f"audio codec {meta.get('acodec')} (expected aac)")
    if (meta.get("width"), meta.get("height")) != (width, height):
        problems.append(f"size {meta.get('width')}x{meta.get('height')} (expected {width}x{height})")
    tol = max(0.25, 3.0 / fps)
    if abs(meta["duration"] - duration) > tol:
        problems.append(f"duration {meta['duration']:.2f}s (expected {duration:.2f}s)")
    if not problems:
        if full_decode:  # catches corruption anywhere, e.g. at segment joins
            cp = run([s.ffmpeg_bin, "-nostdin", "-v", "error", "-i", str(path), "-map", "0:v:0", "-map", "0:a:0",
                      "-f", "null", "-"], timeout=s.render_timeout_s)
            err = (cp.stderr or b"").decode(errors="replace").strip()
            if cp.returncode != 0 or err:
                log.error("decode check failed: %s", err[-1000:])
                problems.append("the video does not decode cleanly")
        else:
            cp = run([s.ffmpeg_bin, "-nostdin", "-v", "error", "-ss", f"{meta['duration'] / 2:.3f}",
                      "-i", str(path), "-frames:v", "1", "-f", "null", "-"], timeout=60)
            if cp.returncode != 0:
                problems.append("the video does not decode")
    if problems:
        raise EditorError("OUTPUT_INVALID", "Rendering produced an invalid file: " + "; ".join(problems),
                          retryable=True)
    return {"ok": True, "size_bytes": path.stat().st_size, **{k: meta[k] for k in
            ("duration", "width", "height", "vcodec", "acodec", "fps")}}
