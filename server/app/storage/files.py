"""File storage (component D).

All on-disk paths are generated by the server. User-supplied names are only kept
as sanitised display strings and never used to build a path.
"""
from __future__ import annotations

import hashlib
import os
import re
import secrets
import shutil
import time
import unicodedata
from pathlib import Path
from typing import AsyncIterator

from ..config import get_settings
from ..errors import EditorError, too_large, unsupported_format

VIDEO_EXTENSIONS = {".mp4", ".mov", ".m4v", ".webm"}
AUDIO_EXTENSIONS = {".mp3", ".m4a", ".aac", ".wav"}  # used from Phase 2


def new_id(prefix: str) -> str:
    return f"{prefix}_{secrets.token_hex(8)}"


def sanitize_filename(name: str, max_len: int = 80) -> str:
    """Return a safe display name: no directories, control chars or odd unicode."""
    name = unicodedata.normalize("NFKC", name or "")
    name = name.replace("\\", "/").split("/")[-1]  # drop any path component
    name = re.sub(r"[\x00-\x1f\x7f]", "", name)
    name = re.sub(r"[^\w.\- ()]", "_", name).strip(" .")
    if not name:
        name = "video"
    if len(name) > max_len:
        stem, ext = os.path.splitext(name)
        name = stem[: max_len - len(ext)] + ext
    return name


def safe_path(root: Path, *parts: str) -> Path:
    """Join parts under root and guarantee the result stays inside root."""
    root = root.resolve()
    candidate = root.joinpath(*parts).resolve()
    if candidate != root and root not in candidate.parents:
        raise EditorError("BAD_PATH", "Invalid file reference.")
    return candidate


def extension_of(name: str) -> str:
    return os.path.splitext(name)[1].lower()


def check_extension(name: str, allowed: set[str]) -> str:
    ext = extension_of(name)
    if ext not in allowed:
        raise unsupported_format(
            f"Your video format isn't supported ({ext or 'no extension'}). Use MP4, MOV or WEBM."
        )
    return ext


async def save_stream(stream: AsyncIterator[bytes], dest: Path, max_bytes: int) -> tuple[int, str]:
    """Write an incoming byte stream to dest, enforcing a size limit. Returns (size, sha256)."""
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_suffix(dest.suffix + ".part")
    h = hashlib.sha256()
    size = 0
    try:
        with open(tmp, "wb") as f:
            async for chunk in stream:
                if not chunk:
                    continue
                size += len(chunk)
                if size > max_bytes:
                    raise too_large(max_bytes // (1024 * 1024))
                h.update(chunk)
                f.write(chunk)
        if size == 0:
            raise EditorError("EMPTY_FILE", "The uploaded file is empty.")
        os.replace(tmp, dest)
    except BaseException:
        tmp.unlink(missing_ok=True)
        raise
    return size, h.hexdigest()


def uploads_dir() -> Path:
    return get_settings().data_dir / "uploads"


def cache_dir(sha256: str) -> Path:
    if not re.fullmatch(r"[0-9a-f]{64}", sha256):
        raise EditorError("BAD_PATH", "Invalid cache key.")
    d = get_settings().data_dir / "cache" / sha256[:2] / sha256
    d.mkdir(parents=True, exist_ok=True)
    return d


def job_dir(job_id: str) -> Path:
    if not re.fullmatch(r"j_[0-9a-f]{16}", job_id):
        raise EditorError("BAD_PATH", "Invalid job reference.")
    d = get_settings().data_dir / "jobs" / job_id
    d.mkdir(parents=True, exist_ok=True)
    return d


def cleanup_expired(protected_paths: set[Path] | None = None) -> dict:
    """Delete files older than the retention policy. Returns counts for logging."""
    s = get_settings()
    now = time.time()
    protected = {p.resolve() for p in (protected_paths or set())}
    removed = {"uploads": 0, "jobs": 0, "tmp": 0, "cache": 0}

    def expired(p: Path, hours: float) -> bool:
        try:
            return now - p.stat().st_mtime > hours * 3600
        except FileNotFoundError:
            return False

    for f in (s.data_dir / "uploads").glob("*"):
        if f.resolve() not in protected and expired(f, s.upload_retention_h):
            f.unlink(missing_ok=True)
            removed["uploads"] += 1
    for d in (s.data_dir / "jobs").glob("j_*"):
        if d.resolve() not in protected and expired(d, s.render_retention_h):
            shutil.rmtree(d, ignore_errors=True)
            removed["jobs"] += 1
    for f in (s.data_dir / "tmp").rglob("*"):  # by each file's own age (active uploads keep growing)
        if f.is_file() and expired(f, s.tmp_retention_h):
            f.unlink(missing_ok=True)
            removed["tmp"] += 1
    # analysis cache follows upload retention (it is cheap to recompute)
    # analysis results and rendered segments (cache/<xx>/<sha>/, cache/segments/<key>.mov)
    for d in (s.data_dir / "cache").glob("*/*"):
        if expired(d, s.upload_retention_h):
            shutil.rmtree(d, ignore_errors=True) if d.is_dir() else d.unlink(missing_ok=True)
            removed["cache"] += 1
    return removed
